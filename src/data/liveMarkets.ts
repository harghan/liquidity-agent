export async function fetchLiveMarketsFromApi(): Promise<Record<string, MarketEvent>> {
  try {
    const res = await fetch('/api/markets', { method: 'GET' });
    if (res.ok) {
      const data = await res.json();
      const events: any[] = data.events || [];
      if (events.length > 0) {
        const merged: Record<string, MarketEvent> = { ...INITIAL_INSTITUTIONAL_MARKETS };
        for (const e of events) {
          const key = (e.id || e.slug || e.title).toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 32);
          merged[key] = {
            id: key,
            name: e.title || e.name,
            category: e.category || 'Global Events',
            polyMid: Number(e.poly_mid || e.polyMid || 0.5),
            kalshiMid: Number(e.kalshi_mid || e.kalshiMid || 0.48),
            baseVwap: Number(e.poly_mid || 0.5),
            liquidityUsd: Number(e.liquidity_usd || e.liquidityUsd || 5000000),
            volumeUsd: Number(e.volume_usd || e.volumeUsd || 10000000),
            spreadBps: Number(e.spread_bps || e.spreadBps || 200),
          };
        }
        return merged;
      }
    }
  } catch (err) {
    console.warn('Live market API fetch fallback to institutional cache:', err);
  }
  return INITIAL_INSTITUTIONAL_MARKETS;
}
